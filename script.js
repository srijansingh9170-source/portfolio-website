/* ============================================================
   COPY EMAIL BUTTON
   ============================================================ */
(function(){
  var btn = document.getElementById("copyEmailBtn");
  if (!btn) return;

  function fallbackCopy(text){
    var textarea = document.createElement("textarea");
    textarea.value = text;
    textarea.setAttribute("readonly", "");
    textarea.style.position = "fixed";
    textarea.style.left = "-9999px";
    document.body.appendChild(textarea);
    textarea.select();
    try{ document.execCommand("copy"); }catch(e){ /* no-op */ }
    document.body.removeChild(textarea);
  }

  btn.addEventListener("click", function(){
    var email = btn.getAttribute("data-email") || "";
    var currentLang = document.documentElement.getAttribute("lang") || DEFAULT_LANG;

    var showDone = function(){
      btn.textContent = t(currentLang, "btn_copy_email_done");
      btn.classList.add("btn-copy-done");
      setTimeout(function(){
        btn.classList.remove("btn-copy-done");
        btn.textContent = t(currentLang, "btn_copy_email");
      }, 1800);
    };

    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(email).then(showDone).catch(function(){
        fallbackCopy(email);
        showDone();
      });
    } else {
      fallbackCopy(email);
      showDone();
    }
  });
})();

/* ============================================================
   SCROLL REVEAL
   ============================================================ */
(function(){
  var revealEls = document.querySelectorAll(".reveal");

  if (prefersReducedMotion || !("IntersectionObserver" in window)) {
    revealEls.forEach(function(el){ el.classList.add("is-visible"); });
    return;
  }

  var observer = new IntersectionObserver(function(entries){
    entries.forEach(function(entry){
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.15, rootMargin: "0px 0px -60px 0px" });

  revealEls.forEach(function(el){ observer.observe(el); });
})();

