var DEFAULT_LANG = "en";
var prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

/* ============================================================
   I18N ENGINE
   ============================================================ */
function t(lang, key){
  var dict = translations[lang] || translations[DEFAULT_LANG];
  if (dict[key] !== undefined) return dict[key];
  return translations[DEFAULT_LANG][key];
}

function applyLanguage(lang){
  if (!translations[lang]) lang = DEFAULT_LANG;

  document.documentElement.setAttribute("lang", lang);
  document.title = t(lang, "page_title");

  var textNodes = document.querySelectorAll("[data-i18n]");
  textNodes.forEach(function(el){
    el.textContent = t(lang, el.getAttribute("data-i18n"));
  });

  var htmlNodes = document.querySelectorAll("[data-i18n-html]");
  htmlNodes.forEach(function(el){
    el.innerHTML = t(lang, el.getAttribute("data-i18n-html"));
  });

  var langSelect = document.getElementById("langSelect");
  if (langSelect) langSelect.value = lang;

  TypingEffect.setStatuses(t(lang, "typing_statuses"));

  var copyBtn = document.getElementById("copyEmailBtn");
  if (copyBtn && !copyBtn.classList.contains("btn-copy-done")) {
    copyBtn.textContent = t(lang, "btn_copy_email");
  }
}

/* ============================================================
   TYPING STATUS LINE
   ============================================================ */
var TypingEffect = (function(){
  var el = document.getElementById("typingOut");
  var statuses = ["training on AI & ML fundamentals"];
  var statusIndex = 0;
  var charIndex = 0;
  var deleting = false;
  var timer = null;

  function tick(){
    if (!el) return;
    var current = statuses[statusIndex % statuses.length];

    if (!deleting) {
      charIndex++;
      el.textContent = current.slice(0, charIndex);

      if (charIndex >= current.length) {
        deleting = true;
        timer = setTimeout(tick, 1600);
        return;
      }
    } else {
      charIndex--;
      el.textContent = current.slice(0, Math.max(charIndex, 0));

      if (charIndex <= 0) {
        deleting = false;
        statusIndex = (statusIndex + 1) % statuses.length;
      }
    }

    timer = setTimeout(tick, deleting ? 30 : 45);
  }

  function start(){
    if (!el) return;
    if (prefersReducedMotion) {
      el.textContent = statuses[0];
      return;
    }
    if (timer) clearTimeout(timer);
    statusIndex = 0;
    charIndex = 0;
    deleting = false;
    el.textContent = "";
    tick();
  }

  function setStatuses(newStatuses){
    statuses = (newStatuses && newStatuses.length) ? newStatuses : statuses;
    if (prefersReducedMotion && el) {
      el.textContent = statuses[0];
    }
    // let the running loop pick up the new array on its next cycle;
    // reset indices so we don't show a mismatched partial word.
    statusIndex = 0;
    charIndex = Math.min(charIndex, statuses[0].length);
  }

  return { start: start, setStatuses: setStatuses };
})();

/* ============================================================
   THEME TOGGLE (light / dark)
   ============================================================ */
(function(){
  var toggle = document.getElementById("themeToggle");
  var icon = document.getElementById("themeIcon");
  if (!toggle) return;

  function syncIcon(){
    var isDark = document.documentElement.getAttribute("data-theme") === "dark";
    toggle.setAttribute("aria-pressed", isDark ? "true" : "false");
    if (icon) icon.textContent = isDark ? "☀️" : "🌙";
  }

  syncIcon();

  toggle.addEventListener("click", function(){
    var current = document.documentElement.getAttribute("data-theme");
    var next = current === "dark" ? "light" : "dark";
    document.documentElement.setAttribute("data-theme", next);
    syncIcon();
  });
})();

